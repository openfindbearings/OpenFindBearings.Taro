// 语音识别结果归一化（ASR 后处理）
// 职责：把离线模型（Vosk）识别出的口头表达转写成适合搜索的关键词——
// 连续中文数字合成阿拉伯数字、口语"杠/斜杠"转成符号，减少型号误输入。
// 说明：仅做文本后处理，无法弥补模型漏识别的字符。

/** 中文数字到阿拉伯数字映射（含口语 两/幺） */
const CN_NUM_MAP: Record<string, string> = {
  零: '0',
  〇: '0',
  一: '1',
  二: '2',
  两: '2',
  三: '3',
  四: '4',
  五: '5',
  六: '6',
  七: '7',
  八: '8',
  九: '9',
  幺: '1'
}

/** 中文数字字符类别（正则字符类用） */
const CN_NUM_CLASS = '零〇一二两三四五六七八九幺'

/** 连续中文数字序列（允许内部空格分隔），至少 2 个才转，防"三环"等单字词误伤 */
const CN_NUM_SEQ_RE = new RegExp(`([${CN_NUM_CLASS}](?:\\s*[${CN_NUM_CLASS}])+)`, 'g')

/**
 * 将识别文本归一化为搜索关键词
 * @example
 *   "六二零五"        => "6205"
 *   "六 二 零 五"     => "6205"（内部空格消除）
 *   "6205杠2RS"       => "6205-2RS"
 *   "6205斜杠2Z"      => "6205/2Z"
 *   "三环轴承"        保持"三环轴承"（单字数字不转）
 */
export function normalizeAsrText(raw: string): string {
  let s = raw.trim()
  // 连续中文数字（含空格分隔）合成阿拉伯数字
  s = s.replace(CN_NUM_SEQ_RE, (m) => {
    return [...m.replace(/\s/g, '')].map((c) => CN_NUM_MAP[c]).join('')
  })
  // 先"斜杠"后"杠"，避免"斜杠"里的"杠"先被转成"-"
  s = s.replace(/\s*斜杠\s*/g, '/')
  s = s.replace(/\s*杠\s*/g, '-')
  // 收敛连续空白为单空格
  return s.replace(/\s+/g, ' ').trim()
}